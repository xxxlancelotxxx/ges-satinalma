const translationCache = new Map<string, string>();
const TR_CHARS_REGEX = /[çğıöşüÇĞİÖŞÜ]/;
const CYRILLIC_ONLY_REGEX = /^[\s\d\p{P}\p{S}\u0400-\u04FF]+$/u;
const HAS_LATIN_OR_TR = /[a-zA-ZçğıöşüÇĞİÖŞÜ]/;

export function translateTextToRu(rawText: string): string {
  if (!rawText || rawText.length < 2) return rawText;
  if (!HAS_LATIN_OR_TR.test(rawText) || CYRILLIC_ONLY_REGEX.test(rawText)) return rawText;

  const match = rawText.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return rawText;
  const [, leading, core, trailing] = match;
  if (!core) return rawText;

  const cached = translationCache.get(core);
  if (cached !== undefined) {
    return leading + cached + trailing;
  }

  // 1. Exact match (case-sensitive, then case-insensitive)
  if (EXACT_RU_MAP[core]) {
    const res = EXACT_RU_MAP[core];
    translationCache.set(core, res);
    return leading + res + trailing;
  }
  const lower = core.toLowerCase();
  const exactLower = EXACT_RU_LOWER_MAP.get(lower);
  if (exactLower) {
    translationCache.set(core, exactLower);
    return leading + exactLower + trailing;
  }

  // 2. Regex pattern rules for dynamic strings
  for (const [regex, replacement] of PATTERN_RU_RULES) {
    if (regex.test(core)) {
      const res = typeof replacement === 'function'
        ? core.replace(regex, replacement)
        : core.replace(regex, replacement);
      translationCache.set(core, res);
      return leading + res + trailing;
    }
  }

  // 3. Phrase replacements if string contains Turkish characters or known Turkish phrases
  if (TR_CHARS_REGEX.test(core)) {
    let result = core;
    let changed = false;
    for (const [trPhrase, ruPhrase] of PHRASE_RU_PAIRS) {
      if (result.includes(trPhrase)) {
        result = result.split(trPhrase).join(ruPhrase);
        changed = true;
      }
    }
    if (changed) {
      translationCache.set(core, result);
      return leading + result + trailing;
    }
  }

  return rawText;
}

// WeakMaps to track original TR values on DOM Text nodes and Elements so switching RU <-> TR is 100% lossless
const textNodeMap = new WeakMap<Text, { tr: string; ru: string }>();
const elementAttrMap = new WeakMap<Element, Record<string, { tr: string; ru: string }>>();

const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'CODE', 'PRE']);
const TRANSLATABLE_ATTRS = ['placeholder', 'title', 'aria-label'] as const;

function processTextNode(node: Text, lang: 'TR' | 'RU') {
  const parent = node.parentElement;
  if (!parent || SKIP_TAGS.has(parent.tagName)) return;
  if (parent.closest('[data-no-translate="true"]')) return;

  const current = node.data;
  if (!current || !current.trim()) return;

  const record = textNodeMap.get(node);

  if (lang === 'RU') {
    if (record && current === record.ru) {
      return; // Already translated
    }
    // Preserve <option> value attribute before mutating display text
    if (parent.tagName === 'OPTION' && !parent.hasAttribute('value')) {
      parent.setAttribute('value', parent.textContent || '');
    }
    const sourceTr = record && current === record.tr ? record.tr : current;
    const translated = translateTextToRu(sourceTr);
    if (translated !== sourceTr) {
      textNodeMap.set(node, { tr: sourceTr, ru: translated });
      node.data = translated;
    }
  } else {
    // Restore original Turkish text when lang === 'TR'
    if (record && current === record.ru) {
      node.data = record.tr;
    }
  }
}

function processElementAttrs(el: Element, lang: 'TR' | 'RU') {
  if (SKIP_TAGS.has(el.tagName)) return;
  let attrRecords = elementAttrMap.get(el);

  for (const attr of TRANSLATABLE_ATTRS) {
    const val = el.getAttribute(attr);
    if (!val || !val.trim()) continue;

    const existing = attrRecords?.[attr];
    if (lang === 'RU') {
      if (existing && val === existing.ru) continue;
      const sourceTr = existing && val === existing.tr ? existing.tr : val;
      const translated = translateTextToRu(sourceTr);
      if (translated !== sourceTr) {
        if (!attrRecords) {
          attrRecords = {};
          elementAttrMap.set(el, attrRecords);
        }
        attrRecords[attr] = { tr: sourceTr, ru: translated };
        el.setAttribute(attr, translated);
      }
    } else {
      if (existing && val === existing.ru) {
        el.setAttribute(attr, existing.tr);
      }
    }
  }
}

function walkAndTranslate(root: Node, lang: 'TR' | 'RU') {
  if (root.nodeType === Node.TEXT_NODE) {
    processTextNode(root as Text, lang);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) {
    return;
  }
  if (root.nodeType === Node.ELEMENT_NODE) {
    const el = root as Element;
    if (SKIP_TAGS.has(el.tagName)) return;
    processElementAttrs(el, lang);
  }

  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT
  );

  let current: Node | null = walker.nextNode();
  while (current) {
    if (current.nodeType === Node.TEXT_NODE) {
      processTextNode(current as Text, lang);
    } else if (current.nodeType === Node.ELEMENT_NODE) {
      processElementAttrs(current as Element, lang);
    }
    current = walker.nextNode();
  }
}

export function useAutoRuDomTranslation(language: 'TR' | 'RU') {
  useEffect(() => {
    if (typeof document === 'undefined') return;

    // Initial pass over document.body
    walkAndTranslate(document.body, language);

    if (language !== 'RU') {
      return;
    }

    let isInternalMutation = false;
    const observer = new MutationObserver((mutations) => {
      if (isInternalMutation) return;
      isInternalMutation = true;
      try {
        for (const m of mutations) {
          if (m.type === 'characterData' && m.target.nodeType === Node.TEXT_NODE) {
            processTextNode(m.target as Text, 'RU');
          } else if (m.type === 'attributes' && m.target.nodeType === Node.ELEMENT_NODE) {
            processElementAttrs(m.target as Element, 'RU');
          } else if (m.type === 'childList') {
            m.addedNodes.forEach((added) => {
              walkAndTranslate(added, 'RU');
            });
          }
        }
      } finally {
        isInternalMutation = false;
      }
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['placeholder', 'title', 'aria-label']
    });

    return () => {
      observer.disconnect();
    };
  }, [language]);
}
